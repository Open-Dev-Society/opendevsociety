// Regenerates src/app/(site)/manifesto/frames.ts: the manifesto figure's three dithered panels.
// The simulation is deterministic (fixed seed), so it runs here once instead of on every render
// (7000 steps blow the Workers CPU limit). Run after changing figure.ts: npx tsx scripts/manifesto-figure.ts
import { writeFileSync } from "node:fs";
import { figureFrames } from "../src/app/(site)/manifesto/figure";

const out = `// Generated by scripts/manifesto-figure.ts from figure.ts. Do not edit.\nexport const FRAMES: readonly string[] = ${JSON.stringify(figureFrames(), null, 2)};\n`;
writeFileSync(new URL("../src/app/(site)/manifesto/frames.ts", import.meta.url), out);
console.log("wrote frames.ts");
